import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const directory = path.join(root, 'skills/brclio-pay-integrate');
await mkdir(path.join(directory, 'assets'), { recursive: true });
for (const name of ['payment-client.mjs', 'webhook-handler.mjs']) {
  await writeFile(path.join(directory, 'assets', name), await readFile(path.join(root, 'examples', name)));
}
const names = ['SKILL.md', 'references/integration.md', 'scripts/inspect-platform.mjs', 'scripts/integration-client.mjs', 'assets/payment-client.mjs', 'assets/webhook-handler.mjs'];
const files = {};
for (const name of names) files[`brclio-pay-integrate/${name}`] = await readFile(path.join(directory, name), 'utf8');
await writeFile(path.join(root, 'src/skill-data.ts'), '// Generated by scripts/build-skill.mjs; do not edit by hand.\nexport const skillFiles: Record<string, string> = ' + JSON.stringify(files, null, 2) + ';\n');
